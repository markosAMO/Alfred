#!/usr/bin/env bash
#
# Alfred skill registry.
#
# Resolves every skill to a path, repository override first, and writes the result as a
# table to .alfred/skill-registry.md. The table is derived from what is on disk, so it is
# never committed: init writes it, the session hook keeps it current, and a clone without
# it gets one the first time an agent opens the repository.
#
#   registry.sh write   resolve and rewrite the registry
#   registry.sh check   compare the registry with the disk; exit 1 when they differ
#   registry.sh list    print the resolved table, write nothing
#   registry.sh sync    write only when missing or stale; never fails; for session hooks

set -euo pipefail

ALFRED_HOME="${ALFRED_HOME:-$HOME/.config/alfred}"
REGISTRY_REL=".alfred/skill-registry.md"
LOCAL_ROOT_REL=".alfred/skills"
HEADER='<!-- Generated by registry.sh. Do not edit: ask the orchestrator for `registry`, or run registry.sh write --force. -->'

mode=""
cwd="$PWD"
quiet=false
force=false
gitignore=true

usage() {
  cat <<'EOF'
usage: registry.sh <write|check|list|sync> [--cwd <dir>] [--quiet] [--force] [--no-gitignore]

  write          resolve every skill and rewrite .alfred/skill-registry.md
  check          compare the registry with what is on disk; exit 1 when they differ
  list           print the resolved table without writing anything
  sync           write only when the registry is missing or stale; for session hooks

  --cwd <dir>    repository to operate on (default: the current directory)
  --quiet        print nothing except errors and the one-line sync notice
  --force        write even when nothing changed
  --no-gitignore do not add the registry to the repository's .gitignore

exit codes: 0 ok, 1 check found differences, 2 error, 3 not an Alfred repository
EOF
}

say()  { $quiet || printf '%s\n' "$*"; }
fail() { printf 'registry: %s\n' "$1" >&2; exit "${2:-2}"; }

# sync is run by hooks from whatever directory the agent opened. Refusing quietly is the
# right answer there; for the other modes the user asked for something and gets told why
# it did not happen.
skip() {
  if [ "$mode" = sync ]; then exit 0; fi
  fail "$*" 3
}

parse_args() {
  [ $# -gt 0 ] || { usage >&2; exit 2; }
  mode="$1"; shift
  case "$mode" in
    write|check|list|sync) ;;
    -h|--help|help) usage; exit 0 ;;
    *) usage >&2; fail "unknown mode: $mode" ;;
  esac
  while [ $# -gt 0 ]; do
    case "$1" in
      --cwd)          [ $# -ge 2 ] || fail "--cwd requires a value"; cwd="$2"; shift 2 ;;
      --quiet|-q)     quiet=true; shift ;;
      --force|-f)     force=true; shift ;;
      --no-gitignore) gitignore=false; shift ;;
      *) usage >&2; fail "unknown argument: $1" ;;
    esac
  done
}

resolve_repo() {
  cwd="$(cd "$cwd" 2>/dev/null && pwd -P)" || skip "no such directory: $cwd"
  local home; home="$(cd "$HOME" && pwd -P)"
  [ "$cwd" != "/" ] && [ "$cwd" != "$home" ] || skip "refusing to run in $cwd"
  [ -d "$cwd/.alfred" ] || skip "$cwd is not an Alfred repository (no .alfred/); run init first"
}

# One scalar from .alfred/config.yaml, by key name. The keys read here are unique in the
# file, so a flat match is enough and no YAML parser is needed.
config_value() {
  local file="$cwd/.alfred/config.yaml"
  [ -f "$file" ] || return 0
  sed -n -E "s/^[[:space:]]*$1:[[:space:]]*//p" "$file" | head -n 1 | tr -d '"'"'"
}

expand_home() { printf '%s' "${1/#\~/$HOME}"; }

display_path() {
  case "$1" in
    "$HOME"/*) printf '~%s' "${1#"$HOME"}" ;;
    *)         printf '%s' "$1" ;;
  esac
}

global_root() {
  local configured; configured="$(config_value global_root)"
  local root; root="$(expand_home "${configured:-$ALFRED_HOME/skills}")"
  printf '%s' "${root%/}"
}

# name<TAB>path<TAB>source, one line per skill, sorted by name. Local rows are emitted
# first and the stable sort keeps them ahead of a global row with the same name, so the
# first occurrence of each name is the one that wins.
resolve() {
  local root dir name
  root="$(global_root)"
  {
    for dir in "$cwd/$LOCAL_ROOT_REL"/*/; do
      [ -f "${dir}SKILL.md" ] || continue
      name="$(basename "$dir")"
      [ "$name" != "_shared" ] || continue
      printf '%s\t%s\t%s\n' "$name" "$LOCAL_ROOT_REL/$name/SKILL.md" local
    done
    for dir in "$root"/*/; do
      [ -f "${dir}SKILL.md" ] || continue
      name="$(basename "$dir")"
      [ "$name" != "_shared" ] || continue
      printf '%s\t%s\t%s\n' "$name" "$(display_path "$root/$name/SKILL.md")" global
    done
  } | sort -s -t "$(printf '\t')" -k1,1 | awk -F'\t' '!seen[$1]++'
}

render() {
  printf '%s\n\n| skill | path | source |\n|---|---|---|\n' "$HEADER"
  awk -F'\t' '{ printf "| %s | %s | %s |\n", $1, $2, $3 }'
}

# Table rows back to name<TAB>path<TAB>source, header row excluded.
rows() {
  [ -f "$1" ] || return 0
  sed -n -E 's/^\| ([^ |]+) \| ([^|]+[^ |]) \| ([^ |]+) \|$/\1\t\2\t\3/p' "$1" | grep -v "^skill$(printf '\t')" || true
}

describe_changes() {
  awk -F'\t' -v oldfile="$1" '
    function label(v) { split(v, a, "\t"); return a[1] " (" a[2] ")" }
    FILENAME == oldfile { old[$1] = $2 "\t" $3; next }
    { new[$1] = $2 "\t" $3 }
    END {
      for (n in new) if (!(n in old)) print "added    " n ": " label(new[n])
      for (n in old) if (!(n in new)) print "removed  " n ": " label(old[n])
      for (n in new) if ((n in old) && old[n] != new[n]) print "changed  " n ": " label(old[n]) " -> " label(new[n])
    }' "$1" "$2" | sort
}

ensure_gitignore() {
  $gitignore || return 0
  [ -d "$cwd/.git" ] || [ -f "$cwd/.git" ] || return 0
  local file="$cwd/.gitignore"
  if [ -f "$file" ] && grep -qxF -e "$REGISTRY_REL" -e "/$REGISTRY_REL" "$file"; then return 0; fi
  local tmp="$file.tmp.$$"
  {
    if [ -f "$file" ]; then
      cat "$file"
      [ -z "$(tail -c 1 "$file")" ] || printf '\n'
    fi
    printf '%s\n' "$REGISTRY_REL"
  } > "$tmp"
  mv -f "$tmp" "$file"
  say "added $REGISTRY_REL to .gitignore"
}

count_rows() { grep -c . "$1" 2>/dev/null || true; }

# Writes the registry from the resolved table in $1 when it differs from what is on disk
# (or always, with --force). Prints the changes and returns 0 when it wrote, 1 otherwise.
write_if_stale() {
  local table="$1" registry="$cwd/$REGISTRY_REL"
  local tmp="$cwd/.alfred/.skill-registry.tmp.$$"
  render < "$table" > "$tmp"
  if ! $force && [ -f "$registry" ] && cmp -s "$tmp" "$registry"; then
    rm -f "$tmp"
    return 1
  fi
  local old_rows; old_rows="$(mktemp)"
  rows "$registry" > "$old_rows"
  mv -f "$tmp" "$registry"
  describe_changes "$old_rows" "$table" > "$changes"
  rm -f "$old_rows"
  return 0
}

cmd_list() {
  resolve | render
}

cmd_write() {
  local table; table="$(mktemp)"; resolve > "$table"
  if write_if_stale "$table"; then
    $quiet || cat "$changes"
    say "registry written: $(count_rows "$table") skills, $REGISTRY_REL"
  else
    say "registry up to date: $(count_rows "$table") skills"
  fi
  rm -f "$table"
  ensure_gitignore
}

cmd_check() {
  local table registry="$cwd/$REGISTRY_REL"
  table="$(mktemp)"; resolve > "$table"
  if [ ! -f "$registry" ]; then
    rm -f "$table"
    say "registry missing: $REGISTRY_REL; ask the orchestrator for registry"
    return 1
  fi
  local current; current="$(mktemp)"; rows "$registry" > "$current"
  local diff; diff="$(describe_changes "$current" "$table")"
  rm -f "$table" "$current"
  if [ -n "$diff" ]; then
    say "registry is stale:"
    $quiet || printf '%s\n' "$diff" | sed 's/^/  /'
    say "fix: ask the orchestrator for registry"
    return 1
  fi
  say "registry matches the skills on disk"
}

# Never fails and never blocks a session: whatever goes wrong is one line on stderr.
cmd_sync() {
  local policy; policy="$(config_value registry_hook)"
  case "${policy:-sync}" in
    off) return 0 ;;
    check)
      local table registry="$cwd/$REGISTRY_REL"
      table="$(mktemp)"; resolve > "$table"
      local current; current="$(mktemp)"; rows "$registry" > "$current"
      if [ ! -f "$registry" ] || [ -n "$(describe_changes "$current" "$table")" ]; then
        printf 'Alfred: skill registry is stale or missing; ask the orchestrator for registry\n'
      fi
      rm -f "$table" "$current"
      return 0 ;;
    sync) ;;
    *) printf 'Alfred: unknown skills.registry_hook value %s; using sync\n' "$policy" >&2 ;;
  esac
  local table existed=false; table="$(mktemp)"; resolve > "$table"
  [ ! -f "$cwd/$REGISTRY_REL" ] || existed=true
  if write_if_stale "$table"; then
    if $existed; then
      printf 'Alfred: skill registry updated (%s skills): %s\n' \
        "$(count_rows "$table")" "$(paste -sd ';' "$changes" | sed 's/;/; /g; s/  */ /g')"
    else
      printf 'Alfred: skill registry created (%s skills): %s\n' "$(count_rows "$table")" "$REGISTRY_REL"
    fi
  fi
  rm -f "$table"
  ensure_gitignore
}

main() {
  parse_args "$@"
  resolve_repo
  changes="$(mktemp)"
  trap 'rm -f "$changes"' EXIT
  case "$mode" in
    list)  cmd_list ;;
    write) cmd_write ;;
    check) cmd_check ;;
    sync)  cmd_sync || { printf 'Alfred: skill registry sync failed\n' >&2; exit 0; } ;;
  esac
}

main "$@"
