// Package generated keeps a manifest (generated.json) of the files and keys a registration
// run wrote into agent directories, so a later run can remove what it no longer produces.
// Removal follows the manifest and its hashes, never a name prefix, so a file the user wrote
// (even one called alfred-notes) is reported and left alone.
package generated

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"io/fs"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

// Agent is what one agent received: files on disk and keys inside a shared JSON file, each
// mapped to the hash of what was written. Files are removed from disk; keys are dropped.
type Agent struct {
	Files map[string]string `json:"files,omitempty"`
	Keys  map[string]string `json:"keys,omitempty"`
}

// Manifest is the generated.json of one scope (the machine or a repository).
type Manifest struct {
	Agents map[string]Agent `json:"agents"`
}

// Read loads a scope's manifest; a missing file returns nil with no error. An undecodable
// manifest is an error, because treating it as absent would abandon every file it claims.
func Read(path string) (*Manifest, error) {
	data, err := os.ReadFile(path)
	if errors.Is(err, fs.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, fmt.Errorf("reading %s: %w", path, err)
	}

	var manifest Manifest
	if err := json.Unmarshal(data, &manifest); err != nil {
		return nil, fmt.Errorf("reading %s: %w", path, err)
	}
	return &manifest, nil
}

// Write saves the manifest as indented JSON at path. Paths inside it are absolute, because
// at machine scope the generated files live outside the manifest's directory.
func (m *Manifest) Write(path string) error {
	data, err := json.MarshalIndent(m, "", "  ")
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, append(data, '\n'), 0o644)
}

// agent returns the named agent's section, or an empty one when the manifest is nil.
func (m *Manifest) agent(name string) Agent {
	if m == nil {
		return Agent{}
	}
	return m.Agents[name]
}

// Set accumulates what one run generated, per agent, as it writes. It can also rebuild a
// manifest from files a caller can prove an earlier version wrote.
type Set struct {
	agents map[string]Agent
}

// NewSet returns an empty Set.
func NewSet() *Set { return &Set{agents: map[string]Agent{}} }

// AddFile records a file this run wrote, with the hash of the bytes it wrote.
func (s *Set) AddFile(agent, path string, content []byte) {
	section := s.agent(agent)
	if section.Files == nil {
		section.Files = map[string]string{}
	}
	section.Files[path] = hash(content)
	s.agents[agent] = section
}

// AddKey records an agent key this run set, with the hash of the value it set.
func (s *Set) AddKey(agent, key string, value []byte) {
	section := s.agent(agent)
	if section.Keys == nil {
		section.Keys = map[string]string{}
	}
	section.Keys[key] = hash(value)
	s.agents[agent] = section
}

// ForgetFiles drops file paths this run turned out not to write (collisions found by
// PlanFiles), so the manifest never claims a file the user wrote.
func (s *Set) ForgetFiles(agent string, paths []string) {
	if len(paths) == 0 {
		return
	}
	section := s.agent(agent)
	for _, path := range paths {
		delete(section.Files, path)
	}
	s.agents[agent] = section
}

// ForgetKeys drops keys this run turned out not to write, like ForgetFiles does for files.
func (s *Set) ForgetKeys(agent string, keys []string) {
	if len(keys) == 0 {
		return
	}
	section := s.agent(agent)
	for _, key := range keys {
		delete(section.Keys, key)
	}
	s.agents[agent] = section
}

// agent returns the named agent's section, or an empty one when the set is nil.
func (s *Set) agent(name string) Agent {
	if s == nil {
		return Agent{}
	}
	return s.agents[name]
}

// Manifest returns a copy of what this run claims, to be written once removal has run.
func (s *Set) Manifest() *Manifest {
	manifest := &Manifest{Agents: make(map[string]Agent, len(s.agents))}
	for name, section := range s.agents {
		manifest.Agents[name] = Agent{
			Files: maps.Clone(section.Files),
			Keys:  maps.Clone(section.Keys),
		}
	}
	return manifest
}

// Sweep classifies what an earlier run left behind for one agent. Remove is claimed and
// unchanged (safe to delete); Modified is claimed but edited (kept). Orphans and Collisions
// carry Alfred's naming but are unclaimed; Collisions are also generated by this run.
type Sweep struct {
	Remove     []string
	Modified   []string
	Orphans    []string
	Collisions []string
}

// sort orders every list so the reported output is deterministic.
func (s *Sweep) sort() {
	for _, list := range []*[]string{&s.Remove, &s.Modified, &s.Orphans, &s.Collisions} {
		slices.Sort(*list)
	}
}

// PlanFiles builds the Sweep for the files an earlier run generated for one agent.
// present must be listed before this run writes anything, so unclaimed files are the user's.
// A claimed file is removed only if its hash still matches, so user edits are never lost.
func PlanFiles(previous *Manifest, current *Set, agent string, present []string) (Sweep, error) {
	claimed := previous.agent(agent).Files
	generated := current.agent(agent).Files

	var sweep Sweep
	for path, recorded := range claimed {
		if _, kept := generated[path]; kept {
			continue
		}
		data, err := os.ReadFile(path)
		if errors.Is(err, fs.ErrNotExist) {
			// Already gone: nothing to remove or report.
			continue
		}
		if err != nil {
			return Sweep{}, fmt.Errorf("reading %s: %w", path, err)
		}
		if hash(data) == recorded {
			sweep.Remove = append(sweep.Remove, path)
		} else {
			sweep.Modified = append(sweep.Modified, path)
		}
	}

	for _, path := range present {
		if _, claimed := claimed[path]; claimed || !named(filepath.Base(path)) {
			continue
		}
		if _, collides := generated[path]; collides {
			sweep.Collisions = append(sweep.Collisions, path)
		} else {
			sweep.Orphans = append(sweep.Orphans, path)
		}
	}

	sweep.sort()
	return sweep, nil
}

// PlanKeys is PlanFiles for an agent that keeps its definitions as keys inside one file.
// present maps each key the file holds now to the bytes of its value.
func PlanKeys(previous *Manifest, current *Set, agent string, present map[string][]byte) Sweep {
	claimed := previous.agent(agent).Keys
	generated := current.agent(agent).Keys

	var sweep Sweep
	for key, recorded := range claimed {
		if _, kept := generated[key]; kept {
			continue
		}
		value, there := present[key]
		if !there {
			continue
		}
		if hash(value) == recorded {
			sweep.Remove = append(sweep.Remove, key)
		} else {
			sweep.Modified = append(sweep.Modified, key)
		}
	}

	for key := range present {
		if _, claimed := claimed[key]; claimed || !named(key) {
			continue
		}
		if _, collides := generated[key]; collides {
			sweep.Collisions = append(sweep.Collisions, key)
		} else {
			sweep.Orphans = append(sweep.Orphans, key)
		}
	}

	sweep.sort()
	return sweep
}

// Scan lists the files in dir that carry Alfred's generated naming, for PlanFiles.
// A missing directory yields no files and no error.
func Scan(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if errors.Is(err, fs.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, fmt.Errorf("reading %s: %w", dir, err)
	}

	var found []string
	for _, entry := range entries {
		if entry.IsDir() || !named(entry.Name()) {
			continue
		}
		found = append(found, filepath.Join(dir, entry.Name()))
	}
	return found, nil
}

// Remove deletes the paths a Sweep found safe to remove; paths already gone are ignored.
func Remove(paths []string) error {
	for _, path := range paths {
		if err := os.Remove(path); err != nil && !errors.Is(err, fs.ErrNotExist) {
			return fmt.Errorf("removing %s: %w", path, err)
		}
	}
	return nil
}

// Named reports whether a name carries Alfred's generated naming; it is the exported form
// of named, for callers that hold agent keys rather than a directory to Scan.
func Named(name string) bool { return named(name) }

// named reports whether a file name or agent key is "alfred" or starts with "alfred-"
// (ignoring the extension); alfredo.md and notes.md do not match.
func named(name string) bool {
	stem := strings.TrimSuffix(name, filepath.Ext(name))
	return stem == "alfred" || strings.HasPrefix(stem, "alfred-")
}

// hash returns the hex-encoded SHA-256 of content.
func hash(content []byte) string {
	sum := sha256.Sum256(content)
	return hex.EncodeToString(sum[:])
}
